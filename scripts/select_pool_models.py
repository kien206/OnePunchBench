"""Curate a model list (data/models/*.yaml) from the registry, deterministically.

    python scripts/select_pool_models.py --max-params-b 2.0 --cap-train 6 --cap-other 2 \
        --must Qwen/Qwen2.5-0.5B Qwen/Qwen2.5-0.5B-Instruct --out data/models/tier_s_round1.yaml

Candidates: on-hub, scored (archive), non-excluded registry rows <= --max-params-b. `--must` ids come
first; the rest of each family (cap: --cap-train for train families, --cap-other for the others) is
filled in order of a seeded hash of the model id. Prints the estimated bf16 disk use.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

from onepunch.data.registry import Registry
from onepunch.data.scores import ScoreTable


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--registry", default="data/registry/registry.parquet")
    ap.add_argument("--scores", default="data/scores/scores.parquet")
    ap.add_argument("--max-params-b", type=float, default=2.0)
    ap.add_argument("--min-params-b", type=float, default=None)
    ap.add_argument("--cap-train", type=int, default=6)
    ap.add_argument("--cap-other", type=int, default=2)
    ap.add_argument("--must", nargs="*", default=[])
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-gb", type=float, default=None, help="drop the largest non-must models until bf16 size fits")
    ap.add_argument("--title", default="")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    reg = Registry.load(args.registry)
    scored = set(ScoreTable.load(args.scores).df["model_id"])
    cand = reg.filter(on_hub=True, max_params_b=args.max_params_b, min_params_b=args.min_params_b).df
    cand = cand[(cand["split"] != "excluded") & cand["model_id"].isin(scored) & (cand["loader"] == "hf")]
    must = {m: i for i, m in enumerate(args.must)}
    key = lambda m: (0, must[m]) if m in must else (1, hashlib.sha256(f"{args.seed}|{m}".encode()).hexdigest())
    chosen = []
    for fam, g in cand.groupby("family"):
        cap = args.cap_train if (g["split"] == "train").all() else args.cap_other
        chosen += sorted(g["model_id"], key=key)[:cap]
    sel = cand[cand["model_id"].isin(chosen)]
    if args.max_gb is not None:
        droppable = sel[~sel["model_id"].isin(must)].sort_values(["params_b", "model_id"], ascending=[False, True])
        for mid, p in zip(droppable["model_id"], droppable["params_b"]):
            if (sel["params_b"] * 2).sum() <= args.max_gb:
                break
            sel = sel[sel["model_id"] != mid]
    sel = sel.sort_values(["split", "family", "model_id"])
    lines = [f"# {args.title}".rstrip(),
             f"# generated by scripts/select_pool_models.py (max_params_b={args.max_params_b}, cap_train={args.cap_train}, "
             f"cap_other={args.cap_other}, seed={args.seed}); all have archive scores and are ungated + on the Hub.",
             f"# {len(sel)} models, ~{(sel['params_b'] * 2).sum():.0f} GB in bf16", "models:"]
    for _, r in sel.iterrows():
        lines.append(f"  - model_id: {r['model_id']}   # {r['split']} / {r['family']} / {r['params_b']:.2f}B")
    Path(args.out).write_text("\n".join(lines) + "\n")
    print(f"{len(sel)} models in {sel['family'].nunique()} families, ~{(sel['params_b'] * 2).sum():.0f} GB bf16 -> {args.out}")
    print(sel["split"].value_counts().to_dict())
    missing = [m for m in args.must if m not in set(sel["model_id"])]
    if missing:
        print("must-include ids not selectable:", missing)


if __name__ == "__main__":
    main()
